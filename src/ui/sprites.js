export const HEART = [
  '.kk.kk.',
  'krrkrrk',
  'krrrrrk',
  'krrrrrk',
  '.krrrk.',
  '..krk..',
  '...k...',
];

export function drawSprite(g, rows, x, y, scale, tint = null) {
  for (let r = 0; r < rows.length; r++) {
    for (let c = 0; c < rows[r].length; c++) {
      const ch = rows[r][c];
      if (ch === '.') continue;
      g.fillStyle = tint && ch !== 'k' ? tint : PAL[ch] || '#f0f';
      g.fillRect(x + c * scale, y + r * scale, scale, scale);
    }
  }
}

// A canvas showing one sprite at an integer scale; CSS sizes it.
export function spriteCanvas(name, { scale = 4, tint = null, cls = '' } = {}) {
  const rows = name === 'heart' ? HEART : SPRITES[name] || SPRITES.scroll;
  const c = document.createElement('canvas');
  c.width = rows[0].length * scale;
  c.height = rows.length * scale;
  if (cls) c.className = cls;
  c.setAttribute('aria-hidden', 'true');
  const g = c.getContext('2d');
  drawSprite(g, rows, 0, 0, scale, tint);
  return c;
}

